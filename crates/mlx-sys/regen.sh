#!/usr/bin/env bash
# Regenerates src/bindings.rs from the vendored mlx-c headers.
#
# Run once after bumping the mlx-c submodule; the output is checked in so normal
# builds need no libclang. Requires `bindgen` (cargo install bindgen-cli) and libclang.
#
# The bindings are generated on a 64-bit LP64 host (x86_64 Linux); they are valid on
# aarch64 macOS too. Headers gated on HAS_FLOAT16/HAS_BFLOAT16 (aarch64 only:
# mlx_array_item_float16, mlx_array_data_float16, ...) are intentionally left out so the
# file is identical on every target; read f16/bf16 data through `mlx_astype` instead.
set -euo pipefail
cd "$(dirname "$0")"

header=vendor/mlx-c/mlx/c/mlx.h
if [[ ! -f $header ]]; then
  echo "missing $header: run 'git submodule update --init crates/mlx-sys/vendor/mlx-c'" >&2
  exit 1
fi

{
  echo "// Generated by crates/mlx-sys/regen.sh from mlx-c $(git -C vendor/mlx-c describe --tags --always) ($(git -C vendor/mlx-c rev-parse --short HEAD))."
  echo "// Do not edit by hand."
  echo
  bindgen "$header" \
    --rust-target 1.85 \
    --rust-edition 2024 \
    --allowlist-function 'mlx_.*' \
    --allowlist-type 'mlx_.*' \
    --allowlist-var 'MLX_.*|mlx_.*' \
    --no-doc-comments \
    --default-enum-style consts \
    -- -I vendor/mlx-c -target x86_64-unknown-linux-gnu
} > src/bindings.rs.tmp
mv src/bindings.rs.tmp src/bindings.rs
echo "wrote src/bindings.rs ($(wc -l < src/bindings.rs) lines)"
