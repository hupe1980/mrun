#!/usr/bin/env bash
# Regenerates src/bindings.rs from the pinned mlx-c headers.
#
# Run once after bumping the mlx-c pin in build.rs or adding a patch; the output is checked in
# so normal builds need no libclang. Requires `bindgen` (cargo install bindgen-cli) and libclang.
#
# The bindings are generated on a 64-bit LP64 host (x86_64 Linux); they are valid on
# aarch64 macOS too. Headers gated on HAS_FLOAT16/HAS_BFLOAT16 (aarch64 only:
# mlx_array_item_float16, mlx_array_data_float16, ...) are intentionally left out so the
# file is identical on every target; read f16/bf16 data through `mlx_astype` instead.
set -euo pipefail
cd "$(dirname "$0")"

pin() { sed -n "/^const MLX_C: Source/,/^};/s/^ *$1: \"\(.*\)\",/\1/p" build.rs; }
commit=$(pin commit)
sha256=$(pin sha256)
version=$(pin version)

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
curl -fsSL "https://github.com/ml-explore/mlx-c/archive/$commit.tar.gz" | gzip -dc > "$work/src.tar"
actual=$(shasum -a 256 "$work/src.tar" | cut -d' ' -f1)
if [[ $actual != "$sha256" ]]; then
  echo "mlx-c $commit: expected sha256 $sha256, got $actual" >&2
  exit 1
fi
tar -xf "$work/src.tar" -C "$work"
src="$work/mlx-c-$commit"
# The bindings cover the patched headers (patches/mlx-c-*.patch add functions, e.g. 0002).
for patch in patches/mlx-c-*.patch; do
  patch -p1 --forward --silent -d "$src" < "$patch"
done

{
  echo "// Generated by crates/mrun-mlx-sys/regen.sh from mlx-c v$version (${commit:0:7})."
  echo "// Do not edit by hand."
  echo
  bindgen "$src/mlx/c/mlx.h" \
    --rust-target 1.85 \
    --rust-edition 2024 \
    --allowlist-function 'mlx_.*' \
    --allowlist-type 'mlx_.*' \
    --allowlist-var 'MLX_.*|mlx_.*' \
    --no-doc-comments \
    --default-enum-style consts \
    -- -I "$src" -target x86_64-unknown-linux-gnu
} > src/bindings.rs.tmp
mv src/bindings.rs.tmp src/bindings.rs
echo "wrote src/bindings.rs ($(wc -l < src/bindings.rs) lines)"
